// Generates src/config/defaults.ts from the markdown docs in src/config/*.md
import fs from "node:fs";
const rd = (f) => fs.readFileSync(new URL(`../src/config/${f}`, import.meta.url), "utf8");
const out = `// AUTO-GENERATED by scripts/gen-defaults.mjs — edit the .md files, then run \`npm run gen:defaults\`.
export const DEFAULT_RUBRIC = ${JSON.stringify(rd("qualified.md"))};
export const SERVICES_REFERENCE = ${JSON.stringify(rd("services.md"))};
export const PRICING_REFERENCE = ${JSON.stringify(rd("pricing.md"))};
`;
fs.writeFileSync(new URL("../src/config/defaults.ts", import.meta.url), out);
console.log("wrote src/config/defaults.ts");
